/** Canonical schemas live here; VibeFlow descriptors and SDK selections are derived. */
import {readFile, readdir, writeFile} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const macro = new URL('../../../javascript_project/macro/', import.meta.url);
const descriptors = new URL('manifests/data/', macro);
const declarations = ['// Generated by packages/era-contracts/scripts/sync-macro-schemas.mjs; do not edit.', 'import {defineDataSchema} from "@vibeflow/plugin";'];
const names = [];
for (const file of (await readdir(descriptors)).filter(file => file.endsWith('.jsonc')).sort()) {
  const descriptor = JSON.parse(await readFile(new URL(file, descriptors), 'utf8'));
  const schema = JSON.parse(await readFile(new URL(`schemas/${descriptor.type_key}.schema.json`, root), 'utf8'));
  await writeFile(new URL(file, descriptors), JSON.stringify({...descriptor, schema}, null, 2) + '\n');
  const name = `contract_0_${names.length}`;
  names.push(name);
  const {kind: _kind, schema: _schema, ...metadata} = descriptor;
  declarations.push(`export const ${name} = defineDataSchema(${JSON.stringify({...metadata, schema})});`);
}
await writeFile(new URL('plugins/contracts/contracts-1.ts', macro), declarations.join('\n') + '\n');
// Keep the package contribution list mechanically synchronized with the descriptor set.
const pluginPath = new URL('plugins/contracts/plugin.ts', macro);
const plugin = await readFile(pluginPath, 'utf8');
await writeFile(pluginPath, plugin.replace(/import \{contract_0_0[^\n]+/, `import {${names.join(', ')}} from "./contracts-1.ts";`).replace(/resources: \[[^\]]*\]/, `resources: [${names.join(', ')}]`));
