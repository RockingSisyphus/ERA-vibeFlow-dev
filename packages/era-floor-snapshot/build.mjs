import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { writeFileSync } from 'node:fs';
import { basename } from 'node:path';
const require = createRequire(new URL('../../app/package.json', import.meta.url));
const ts = require('typescript');
const names = ['floor_snapshot'];
const sources = names.map(name => fileURLToPath(new URL(`../../javascript_project/service/base_lib/domain/${name}.ts`, import.meta.url)));
const program = ts.createProgram(sources, { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, strict: true, skipLibCheck: true, declaration: true, types: [], esModuleInterop: true });
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, { getCanonicalFileName: p => p, getCurrentDirectory: () => process.cwd(), getNewLine: () => '\n' }));
program.emit(undefined, (name, content) => writeFileSync(new URL(basename(name), import.meta.url), '// Generated from Service base_lib/domain; do not edit.\n' + content));
for (const ext of ['js', 'd.ts']) writeFileSync(new URL(`index.${ext}`, import.meta.url), '// Generated exports; do not edit.\n' + names.map(name => `export * from './${name}.js';`).join('\n') + '\n');
